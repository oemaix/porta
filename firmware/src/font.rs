fn glyph_on(ch: u8, col: i32, row: i32) -> bool {
    if !(0..GLYPH_W).contains(&col) || !(0..GLYPH_H).contains(&row) {
        return false;
    }
    let index = if (0x20..0x7f).contains(&ch) {
        (ch - 0x20) as usize
    } else {
        return false;
    };
    GLYPHS[index][col as usize] & (1 << row) != 0
}

/// Ink for `text` inside `rect`. The full-panel item keeps its title on
/// the top edge. Other blocks center the line in the block.
pub fn text_covers(text: &str, rect: &Rect, x: i32, y: i32) -> bool {
    if text.is_empty() {
        return false;
    }
    let left = rect.x as i32;
    let top = rect.y as i32;
    let right = left + rect.w as i32;
    let bottom = top + rect.h as i32;
    if x < left || y < top || x >= right || y >= bottom {
        return false;
    }
    // The full-panel title sits above the volume line at y=12, so it stays 1x.
    let scale = if rect.w >= 320 && rect.h >= 240 {
        1
    } else {
        SCALE
    };
    let origin_x = left + 8;
    let glyph_px_h = GLYPH_H * scale;
    let origin_y = if scale == 1 {
        top + 2
    } else {
        let slack = rect.h as i32 - glyph_px_h;
        top + if slack > 0 { slack / 2 } else { 0 }
    };
    if x < origin_x || y < origin_y {
        return false;
    }
    let dx = x - origin_x;
    let dy = y - origin_y;
    if dy >= glyph_px_h {
        return false;
    }
    let advance = 6 * scale;
    let bytes = text.as_bytes();
    let index = (dx / advance) as usize;
    if index >= bytes.len() {
        return false;
    }
    let gx = dx % advance;
    if gx >= GLYPH_W * scale {
        return false;
    }
    glyph_on(bytes[index], gx / scale, dy / scale)
}

#[cfg(test)]
mod tests {
    use super::text_covers;
    use crate::seam::{FixedText, Rect};

    #[test]
    fn play_inks_a_block_and_not_the_outside() {
        let rect = Rect {
            x: 16,
            y: 48,
            w: 288,
            h: 28,
        };
        let mut text = FixedText::<24>::new();
        text.set("Play");
        let mut hits = 0;
        for y in 48..76 {
            for x in 16..120 {
                if text_covers(text.as_str(), &rect, x, y) {
                    hits += 1;
                }
            }
        }
        assert!(hits > 10);
        assert!(!text_covers(text.as_str(), &rect, 0, 0));
        assert!(!text_covers(" ", &rect, 30, 58));
    }

    #[test]
    fn title_sits_on_the_top_edge() {
        let rect = Rect {
            x: 0,
            y: 0,
            w: 320,
            h: 240,
        };
        let mut hits_top = 0;
        let mut hits_mid = 0;
        for x in 0..80 {
            if text_covers("Tone", &rect, x, 6) {
                hits_top += 1;
            }
            if text_covers("Tone", &rect, x, 120) {
                hits_mid += 1;
            }
        }
        assert!(hits_top > 0);
        assert_eq!(hits_mid, 0);
    }
}
